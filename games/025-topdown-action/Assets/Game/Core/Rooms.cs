    ///                                     │(小扉)
    /// [2 西の回廊: 全滅で小鍵] ──── [1 入口] ──── [3 東の間: 宝箱=小鍵]
    /// </code>
    /// 小鍵は 2 本（西の回廊の全滅・東の間の宝箱）で、どちらの小扉にも使える。前室へ 1 本、宝物庫へもう 1 本が要る。
    /// </summary>
    public static class Rooms
    {
        public const int Entrance = 0;
        public const int West = 1;
        public const int East = 2;
        public const int Vault = 3;
        public const int Antechamber = 4;
        public const int Lair = 5;

